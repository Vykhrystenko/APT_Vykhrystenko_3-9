#include <algorithm>
#include <iostream>
#include <vector>
#include <windows.h>

int main() {
    SetConsoleCP(65001);
    SetConsoleOutputCP(65001);

    std::vector<int> v{ 1, -2, 3, -4, 5 };

    // Початковий фрагмент:
    // std::remove_if перевіряє кожен елемент за допомогою
    // переданого лямбда-виразу.
    // Елементи, які не задовольняють умову видалення,
    // переміщуються на початок діапазону.
    //
    // remove_if не видаляє елементи фізично
    // та не змінює розмір вектора.
    // Він лише повертає ітератор нового логічного кінця.


    const auto newEnd = std::remove_if(
        v.begin(),
        v.end(),
        [](int x) {
            return x < 0;
        }
    );

    std::cout << "Початковий фрагмент:\n";
    std::cout << "Розмір вектора: "<< v.size() << '\n';
    std::cout << "Елементи вектора: ";

    for (int x : v) {
        std::cout << x << ' ';
    }

    std::cout << "\n\n";

    // Виправлення:
    // Для фізичного видалення елементів використовується
    // метод erase(), якому передають новий логічний кінець
    // та початковий кінець вектора.
    //
    // Таким чином, видаляються всі елементи після newEnd,
    // а розмір вектора фактично зменшується.

    v.erase(newEnd, v.end());

    std::cout << "Після виправлення:\n";

    std::cout << "Розмір вектора: "
        << v.size() << '\n';

    std::cout << "Елементи вектора: ";

    for (int x : v) {
        std::cout << x << ' ';
    }

    std::cout << '\n';

    return 0;
}